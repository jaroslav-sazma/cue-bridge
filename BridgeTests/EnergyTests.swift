import Foundation
import Testing

private let start = ContinuousClock.now

@Suite("Energy")
struct EnergyTests {
    // MARK: Summons

    @Test("summons wait while the display sleeps, and its wake asks once for all of them")
    func displaySleep() {
        var gate = SummonGate(displayAwake: true)
        gate.displaySlept()
        let doorbell = gate.ask(.doorbell, at: start)
        let another = gate.ask(.doorbell, at: start + .seconds(1))
        let confirmed = gate.ask(.confirmed, at: start + .seconds(2))
        #expect([doorbell, another, confirmed] == [.deferred, .deferred, .deferred])
        let waited = gate.displayWoke()
        #expect(waited == 3)
        let wake = gate.ask(.wake, at: start + .seconds(3))
        #expect(wake == .summon, "the wake's own ask is the one summon")
        let afterWake = gate.displayWoke()
        #expect(afterWake == 0, "nothing is owed twice")
    }

    @Test("a display asleep at launch holds summons back until it wakes")
    func asleepAtLaunch() {
        var gate = SummonGate(displayAwake: false)
        let held = gate.ask(.confirmed, at: start)
        #expect(held == .deferred)
        _ = gate.displayWoke()
        let woke = gate.ask(.confirmed, at: start)
        #expect(woke == .summon)
    }

    @Test("a fresh Bluetooth confirmation does not summon right after a sync, unless the display slept")
    func reconnectChurn() {
        var gate = SummonGate()
        gate.synced(at: start)
        let churn = gate.ask(.confirmed, at: start + .seconds(30))
        #expect(churn == .recentSync)
        let doorbell = gate.ask(.doorbell, at: start + .seconds(30))
        #expect(doorbell == .summon, "a doorbell is news and always summons")
        let later = gate.ask(.confirmed, at: start + SummonGate.freshSync)
        #expect(later == .summon, "minutes later the mirror may have drifted")

        gate.synced(at: start)
        gate.displaySlept()
        _ = gate.displayWoke()
        let slept = gate.ask(.confirmed, at: start + .seconds(30))
        #expect(slept == .summon, "a sleep in between may hide anything")
    }

    @Test("a new pairing forgets the last sync and what was held back")
    func pairingChanged() {
        var gate = SummonGate()
        gate.synced(at: start)
        gate.pairingChanged()
        let confirmed = gate.ask(.confirmed, at: start + .seconds(1))
        #expect(confirmed == .summon)
        #expect(SummonReason.confirmed.rawValue == "confirmed subscriber")
    }

    // MARK: Input idle

    @Test("with input since the last pass every fire passes at the interval")
    func activeUser() {
        var pacer = IdlePacer(interval: .seconds(5), start: start)
        for step in 1...3 {
            let passed = pacer.fire(at: start + .seconds(5 * step), idle: .seconds(1))
            #expect(passed)
            #expect(pacer.wait == .seconds(5))
        }
    }

    @Test("without input the passes stop and the waits double up to four times the interval")
    func idleUser() {
        var pacer = IdlePacer(interval: .seconds(5), start: start)
        var now = start
        var waits: [Duration] = []
        for _ in 1...4 {
            now += pacer.wait
            let passed = pacer.fire(at: now, idle: .seconds(3600))
            #expect(!passed)
            waits.append(pacer.wait)
        }
        #expect(waits == [.seconds(10), .seconds(20), .seconds(20), .seconds(20)])
        #expect(pacer.ceiling == .seconds(20))
        now += pacer.wait
        let back = pacer.fire(at: now, idle: .seconds(2))
        #expect(back, "input since the last pass brings the pass back")
        #expect(pacer.wait == .seconds(5))
    }

    @Test("input before the last pass and none since skips; an unknown idle time passes")
    func boundary() {
        var pacer = IdlePacer(interval: .seconds(1), start: start)
        let quiet = pacer.fire(at: start + .seconds(1), idle: .seconds(1))
        #expect(!quiet, "the last input came no later than the last pass")
        let unknown = pacer.fire(at: start + .seconds(3), idle: nil)
        #expect(unknown)
        #expect(pacer.lastPass == start + .seconds(3))
    }

    // MARK: Clipboard

    @Test("transient and auto-generated clips are skipped unread, like concealed ones")
    func markers() throws {
        let echo = ClipboardEcho()
        var reads = 0
        let read: () -> String? = {
            reads += 1
            return "secret"
        }
        let transient = PasteboardClip(types: [ClipboardLimits.transientType, "public.utf8-plain-text"], read: read)
        let generated = PasteboardClip(types: [ClipboardLimits.autoGeneratedType], read: read)
        let concealed = PasteboardClip(types: [ClipboardLimits.concealedType, ClipboardLimits.transientType], read: read)
        #expect(reads == 0, "a marked clip is never read")
        #expect(try echo.decide(transient, at: start) == .skip(.transient))
        #expect(try echo.decide(generated, at: start) == .skip(.autoGenerated))
        #expect(try echo.decide(concealed, at: start) == .skip(.concealed))
        let plain = PasteboardClip(types: ["public.utf8-plain-text"], read: read)
        #expect(reads == 1)
        #expect(try echo.decide(plain, at: start) == .send(text: "secret", .small(.clipboardSmall(text: "secret", sensitive: false))))
        #expect(ClipboardLimits.transientType == "org.nspasteboard.TransientType")
        #expect(ClipboardLimits.autoGeneratedType == "org.nspasteboard.AutoGeneratedType")
        #expect(ClipSkip.autoGenerated.rawValue == "auto-generated")
    }

    @Test("the phone's switch keeps the poll disarmed over a session and over Bluetooth alike")
    func phoneSwitch() {
        var machine = ClipboardPublisherMachine(phoneTakesClips: false)
        let session = machine.handle(.sessionStarted)
        let bluetooth = machine.handle(.bluetooth(linked: true))
        #expect(session.isEmpty && bluetooth.isEmpty)
        #expect(machine.idle == .phoneDeclines)
        #expect(ClipboardPublisherMachine.Idle.phoneDeclines.rawValue == "clipboard from the Mac off on the phone")
        let allowed = machine.handle(.phone(clipboardFromMac: true))
        #expect(allowed == [.arm])
        let declined = machine.handle(.phone(clipboardFromMac: false))
        #expect(declined == [.disarm(.phoneDeclines)])
        let ended = machine.handle(.sessionEnded)
        #expect(ended.isEmpty, "nothing scheduled, nothing to tear down")
    }

    @Test("this Mac's switch keeps the poll disarmed whatever the phone allows, and its reason comes first")
    func macSwitch() {
        var machine = ClipboardPublisherMachine(phoneTakesClips: false, macSendsClips: false)
        let session = machine.handle(.sessionStarted)
        let bluetooth = machine.handle(.bluetooth(linked: true))
        let phone = machine.handle(.phone(clipboardFromMac: true))
        #expect(session.isEmpty && bluetooth.isEmpty && phone.isEmpty)
        #expect(machine.idle == .macDeclines)
        #expect(ClipboardPublisherMachine.Idle.macDeclines.rawValue == "clipboard to the phone off on this Mac")
        let allowed = machine.handle(.mac(sendsClips: true))
        #expect(allowed == [.arm])
        let declined = machine.handle(.mac(sendsClips: false))
        #expect(declined == [.disarm(.macDeclines)])
        let sessionAgain = machine.handle(.sessionStarted)
        #expect(sessionAgain.isEmpty, "a session that starts while off brings no pass")
        let phoneOff = machine.handle(.phone(clipboardFromMac: false))
        #expect(phoneOff.isEmpty)
        #expect(machine.idle == .macDeclines)
        #expect(ClipboardPublisherMachine().macSendsClips, "on unless the user turned it off")
    }

    @Test("the hello carries the phone's switch only when given, and a quoted one is malformed")
    func helloSwitch() throws {
        let phone = try BridgeMessage.hello(version: 1, clipboardFromMac: false).encodedBody().body
        let members = try #require(try JSONSerialization.jsonObject(with: phone) as? [String: Any])
        #expect(members["clipboardFromMac"] as? Bool == false)
        #expect(try BridgeMessage.decode(type: "hello", body: phone, sidecar: nil) == .hello(version: 1, clipboardFromMac: false))
        let mac = try BridgeMessage.hello(version: 1).encodedBody().body
        let plain = try #require(try JSONSerialization.jsonObject(with: mac) as? [String: Any])
        #expect(plain["clipboardFromMac"] == nil)
        let quoted = Data(#"{"type":"hello","v":1,"clipboardFromMac":"false"}"#.utf8)
        #expect(throws: (any Error).self) { try BridgeMessage.decode(type: "hello", body: quoted, sidecar: nil) }
    }
}
