import CryptoKit
import Foundation

nonisolated enum ClipboardLimits {
    static let maxBytes = 102_400
    static let concealedType = "org.nspasteboard.ConcealedType"
    static let transientType = "org.nspasteboard.TransientType"
    static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    static func fits(_ text: String) -> Bool {
        text.utf8.count <= maxBytes
    }
}

nonisolated enum ClipSkip: String, Equatable, Sendable {
    case concealed
    case transient
    case autoGenerated = "auto-generated"
    case notText = "not-text"
    case empty
    case tooLarge = "too-large"
    case echo
    case unchanged
}

// The nspasteboard.org markers: a concealed clip is a secret, a transient one is not meant to stay
// (a clipboard manager restoring an entry, an app's private round trip) and an auto-generated one was
// not copied by the user. A marked clip carries no text: it is skipped before its content is ever
// read.
nonisolated struct PasteboardClip: Equatable, Sendable {
    var concealed: Bool
    var transient = false
    var autoGenerated = false
    var text: String?

    init(concealed: Bool, transient: Bool = false, autoGenerated: Bool = false, text: String?) {
        self.concealed = concealed
        self.transient = transient
        self.autoGenerated = autoGenerated
        self.text = text
    }

    init(types: Set<String>, read: () -> String?) {
        concealed = types.contains(ClipboardLimits.concealedType)
        transient = types.contains(ClipboardLimits.transientType)
        autoGenerated = types.contains(ClipboardLimits.autoGeneratedType)
        text = concealed || transient || autoGenerated ? nil : read()
    }
}

// Spec, frame types: `clipboard-small` while its whole plaintext fits one frame, otherwise
// `clipboard-set` over TCP. The Mac never sends `sensitive` (a concealed clip is skipped) and never
// `announce` (every Mac clip is an automatic sync). A clip that waited carries its age either way.
nonisolated enum ClipboardEncoding: Equatable, Sendable {
    case small(Signal)
    case overTcp(BridgeMessage)

    static func plan(_ text: String, ageMs: Int64? = nil) throws -> ClipboardEncoding {
        let small = Signal.clipboardSmall(text: text, sensitive: false, ageMs: ageMs)
        if text.utf8.count <= SignalFrame.maxPlaintextBytes,
            try small.plaintext().count <= SignalFrame.maxPlaintextBytes
        {
            return .small(small)
        }
        return .overTcp(.clipboardSet(text: text, sensitive: false, announce: false, ageMs: ageMs))
    }

    var wireType: String {
        switch self {
        case .small(let signal): signal.name
        case .overTcp(let message): message.type
        }
    }
}

nonisolated enum ClipDecision: Equatable, Sendable {
    case send(text: String, ClipboardEncoding)
    case skip(ClipSkip)
}

// What crossed the bridge last, either way, kept as a digest so no clip text stays in memory. A
// text applied for the phone is tombstoned on top of that, so the pasteboard change its write causes
// is never sent back, even after something else went out in between. The phone needs neither
// rule: it sends a clip only on its user's explicit action.
nonisolated struct ClipboardEcho: Equatable, Sendable {
    static let tombstoneLifetime = Duration.seconds(10)

    private var tombstones: [Data: ContinuousClock.Instant] = [:]
    private var last: Data?

    // Called before the write, so the change it causes already meets the tombstone.
    mutating func applied(_ text: String, at now: ContinuousClock.Instant) {
        let digest = Self.digest(text)
        tombstones = tombstones.filter { $0.value > now }
        tombstones[digest] = now + Self.tombstoneLifetime
        last = digest
    }

    mutating func sent(_ text: String) {
        last = Self.digest(text)
    }

    func decide(_ clip: PasteboardClip, at now: ContinuousClock.Instant, ageMs: Int64? = nil) throws -> ClipDecision {
        if clip.concealed { return .skip(.concealed) }
        if clip.transient { return .skip(.transient) }
        if clip.autoGenerated { return .skip(.autoGenerated) }
        guard let text = clip.text else { return .skip(.notText) }
        if text.isEmpty { return .skip(.empty) }
        guard ClipboardLimits.fits(text) else { return .skip(.tooLarge) }
        let digest = Self.digest(text)
        if let until = tombstones[digest], now < until { return .skip(.echo) }
        if digest == last { return .skip(.unchanged) }
        return .send(text: text, try ClipboardEncoding.plan(text, ageMs: ageMs))
    }

    func liveTombstones(at now: ContinuousClock.Instant) -> Int {
        tombstones.values.count { now < $0 }
    }

    private static func digest(_ text: String) -> Data {
        Data(SHA256.hash(data: Data(text.utf8)))
    }
}

// A copy that found no way to the phone, kept by its changeCount and the moment the poll first saw
// it, so the session that finally carries it can say how old it is. The phone drops a clip older
// than its limit, which is at most an hour, so a debt older than that is forgotten instead of paid.
// The phone is told once per debt that a clip waits, whatever arms and passes follow.
nonisolated struct ClipboardDebt: Equatable, Sendable {
    static let lifetime = Duration.seconds(60 * 60)

    var changeCount: Int
    var observedAt: ContinuousClock.Instant
    var signalled = false

    func expired(at now: ContinuousClock.Instant) -> Bool {
        now - observedAt > Self.lifetime
    }

    func ageMs(at now: ContinuousClock.Instant) -> Int64 {
        let age = now - observedAt
        let (seconds, attoseconds) = age.components
        return max(0, seconds * 1000 + attoseconds / 1_000_000_000_000_000)
    }
}

// The clipboard poll: armed only while this Mac's user lets clips go to the phone and the phone
// takes them (its hello says so, and the last one counts between sessions), a signal path to the
// phone is up (a session or a GATT subscription confirmed as the phone's, never a bare one) and the
// Mac is awake, unlocked and allowed to read the pasteboard, torn down to no timer otherwise. Every
// arming is followed by one pass at once, so a copy made before the phone connected still goes out,
// and so is a session that starts while the poll is already armed over GATT: a clip too large for a
// BLE frame waits for it. A session counts from its hello: a Send to Mac connection never sends an
// active-set.
nonisolated struct ClipboardPublisherMachine: Equatable, Sendable {
    static let intervalSeconds = 1

    enum Event: Equatable, Sendable {
        case sessionStarted
        case sessionEnded
        case bluetooth(linked: Bool)
        case screenSlept
        case screenWoke
        case screenLocked
        case screenUnlocked
        case access(denied: Bool)
        case phone(clipboardFromMac: Bool)
        case mac(sendsClips: Bool)
    }

    enum Idle: String, Equatable, Sendable {
        case macDeclines = "clipboard to the phone off on this Mac"
        case phoneDeclines = "clipboard from the Mac off on the phone"
        case noSignalPath = "no session or confirmed Bluetooth link"
        case accessDenied = "pasteboard access denied"
        case screenAsleep = "screen asleep"
        case screenLocked = "screen locked"
    }

    enum Effect: Equatable, Sendable {
        case arm
        case disarm(Idle)
        case pass
    }

    private(set) var sessionUp = false
    private(set) var bluetoothUp = false
    private(set) var screenAwake: Bool
    private(set) var unlocked: Bool
    private(set) var accessDenied = false
    private(set) var phoneTakesClips: Bool
    private(set) var macSendsClips: Bool
    private(set) var armed = false

    init(screenAwake: Bool = true, unlocked: Bool = true, phoneTakesClips: Bool = true, macSendsClips: Bool = true) {
        self.screenAwake = screenAwake
        self.unlocked = unlocked
        self.phoneTakesClips = phoneTakesClips
        self.macSendsClips = macSendsClips
    }

    var signalPathUp: Bool { sessionUp || bluetoothUp }

    var idle: Idle? {
        if !macSendsClips { return .macDeclines }
        if !phoneTakesClips { return .phoneDeclines }
        if !signalPathUp { return .noSignalPath }
        if accessDenied { return .accessDenied }
        if !screenAwake { return .screenAsleep }
        if !unlocked { return .screenLocked }
        return nil
    }

    mutating func handle(_ event: Event) -> [Effect] {
        var sessionArrived = false
        switch event {
        case .sessionStarted:
            sessionArrived = !sessionUp
            sessionUp = true
        case .sessionEnded: sessionUp = false
        case .bluetooth(let linked): bluetoothUp = linked
        case .screenSlept: screenAwake = false
        case .screenWoke: screenAwake = true
        case .screenLocked: unlocked = false
        case .screenUnlocked: unlocked = true
        case .access(let denied): accessDenied = denied
        case .phone(let clipboardFromMac): phoneTakesClips = clipboardFromMac
        case .mac(let sendsClips): macSendsClips = sendsClips
        }
        if let idle {
            guard armed else { return [] }
            armed = false
            return [.disarm(idle)]
        }
        guard !armed else { return sessionArrived ? [.pass] : [] }
        armed = true
        return [.arm]
    }
}
